#!/usr/bin/env bash
# Generates missing FINIX development secrets into the git-ignored root .env and frontend/.env.local.
#   bash scripts/setup-env.sh                       create/complete the env files (never rotates anything)
#   bash scripts/setup-env.sh --apply-db-password   also set POSTGRES_PASSWORD on an EXISTING dev Postgres (no data is touched)
# Existing values (including your own API keys) are preserved. Secret values are never printed.
# Compatible with macOS' bash 3.2.
set -euo pipefail
umask 077
cd "$(dirname "$0")/.."

ENV_FILE=".env"
FE_FILE="frontend/.env.local"
APPLY_DB=0
[ "${1:-}" = "--apply-db-password" ] && APPLY_DB=1

die() { echo "setup-env: $*" >&2; exit 1; }
command -v openssl >/dev/null 2>&1 || die "openssl is required (macOS: preinstalled / 'brew install openssl'; Debian: 'apt install openssl')."

gen() { openssl rand -hex 32; }                                    # 256 bits from OpenSSL's CSPRNG
value_of() { [ -f "$1" ] && grep -E "^$2=" "$1" | tail -n1 | cut -d= -f2- || true; }
has_value() { [ -n "$(value_of "$1" "$2")" ]; }

SECRETS="POSTGRES_PASSWORD KC_BOOTSTRAP_ADMIN_PASSWORD FINIX_SESSION_SECRET"
# NAME=default for non-secret configuration (written only when missing)
DEFAULTS="NODE_ENV=development
POSTGRES_DB=finix
POSTGRES_USER=finix
KC_BOOTSTRAP_ADMIN_USERNAME=admin
KEYCLOAK_REALM=finix
KEYCLOAK_CLIENT_ID=finix-web
SPRING_PROFILES_ACTIVE=dev
JWT_ISSUER_URI=http://localhost:8081/realms/finix
JWT_JWKS_URI=http://keycloak:8080/realms/finix/protocol/openid-connect/certs
JWT_AUDIENCE=finix-api
APP_ALLOWED_ORIGIN=http://localhost:3000"

tmp="$(mktemp "${ENV_FILE}.XXXXXX")"
trap 'rm -f "$tmp"' EXIT
[ -f "$ENV_FILE" ] && cat "$ENV_FILE" > "$tmp"
[ -s "$tmp" ] && [ -n "$(tail -c1 "$tmp")" ] && echo >> "$tmp"   # ensure trailing newline

added=""; generated=""
header_done=0
add_line() {                                                      # add_line NAME VALUE
  if [ "$header_done" = 0 ]; then printf '\n# --- FINIX local development (generated by scripts/setup-env.sh; git-ignored, never commit) ---\n' >> "$tmp"; header_done=1; fi
  printf '%s=%s\n' "$1" "$2" >> "$tmp"
}
drop_empty() { grep -Ev "^$1=\s*$" "$tmp" > "$tmp.x" || true; mv "$tmp.x" "$tmp"; }

for name in $SECRETS; do
  if ! has_value "$ENV_FILE" "$name"; then
    drop_empty "$name"; add_line "$name" "$(gen)"; generated="$generated $name"
  fi
done
while IFS='=' read -r name val; do
  [ -z "$name" ] && continue
  if ! grep -Eq "^$name=" "$tmp"; then add_line "$name" "$val"; added="$added $name"; fi
done <<< "$DEFAULTS"

# Validate before replacing anything.
for name in $SECRETS POSTGRES_DB POSTGRES_USER KC_BOOTSTRAP_ADMIN_USERNAME JWT_ISSUER_URI JWT_AUDIENCE; do
  grep -Eq "^$name=.+" "$tmp" || die "required variable $name is missing after generation (aborting, nothing written)"
done
for name in $SECRETS; do
  v="$(grep -E "^$name=" "$tmp" | tail -n1 | cut -d= -f2-)"
  [ "${#v}" -ge 32 ] || die "$name is shorter than 32 characters; rotate it with scripts/rotate-secret.sh"
done

if [ -n "$generated$added" ] || [ ! -f "$ENV_FILE" ]; then
  chmod 600 "$tmp"; mv "$tmp" "$ENV_FILE"; trap - EXIT          # atomic replace
else
  rm -f "$tmp"; trap - EXIT
fi
chmod 600 "$ENV_FILE"

# Browser-public configuration only: no secrets here, ever.
if [ ! -f "$FE_FILE" ]; then
  fe="$(mktemp "${FE_FILE}.XXXXXX")"
  cat > "$fe" <<'FEEOF'
# Browser-public configuration. NEVER put passwords, session secrets or client secrets in NEXT_PUBLIC_* variables.
NEXT_PUBLIC_APP_ORIGIN=http://localhost:3000
NEXT_PUBLIC_API_BASE_URL=http://localhost:8080
NEXT_PUBLIC_OIDC_AUTHORITY=http://localhost:8081/realms/finix
NEXT_PUBLIC_OIDC_CLIENT_ID=finix-web
FEEOF
  chmod 600 "$fe"; mv "$fe" "$FE_FILE"; fe_msg="created $FE_FILE"
else
  fe_msg="kept existing $FE_FILE"
fi
if grep -Eq '^NEXT_PUBLIC_[A-Z_]*(SECRET|PASSWORD|KEY|TOKEN)=' "$FE_FILE" 2>/dev/null; then
  echo "setup-env: WARNING: $FE_FILE has a NEXT_PUBLIC_ variable that looks secret. Public variables are shipped to every browser." >&2
fi

# An existing Postgres volume keeps the password it was initialised with; .env alone does not change it.
pg_volume=0
docker volume ls -q 2>/dev/null | grep -q "_finix_pg$" && pg_volume=1 || true
if [ "$APPLY_DB" = 1 ]; then
  command -v docker >/dev/null || die "docker is required for --apply-db-password"
  cid="$(docker compose ps -q postgres 2>/dev/null || true)"
  [ -n "$cid" ] || die "the postgres container is not running (docker compose up -d postgres), nothing applied"
  pw="$(value_of "$ENV_FILE" POSTGRES_PASSWORD)"; user="$(value_of "$ENV_FILE" POSTGRES_USER)"
  # Over the container's local socket; the password travels on stdin, never in argv or logs. Data is not touched.
  printf "ALTER USER \"%s\" PASSWORD '%s';\n" "$user" "$pw" | docker compose exec -T postgres psql -U "$user" -d postgres -v ON_ERROR_STOP=1 -q >/dev/null
  echo "Applied POSTGRES_PASSWORD to the running dev database (data unchanged)."
elif [ "$pg_volume" = 1 ] && echo "$generated" | grep -q POSTGRES_PASSWORD; then
  echo "NOTE: a Postgres data volume already exists and still uses its OLD password."
  echo "      Run: bash scripts/setup-env.sh --apply-db-password   (postgres must be running; no data is deleted)"
fi

echo "FINIX environment ready."
[ -n "$generated" ] && echo "  generated secrets:$generated (values not shown; see $ENV_FILE, mode 600)" || echo "  all secrets already present; none changed"
[ -n "$added" ] && echo "  added defaults:$added"
echo "  $fe_msg"
